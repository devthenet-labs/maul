package playwright

import (
	_ "embed"
	"encoding/json"
	"strconv"
	"strings"
)

// pageFunctions is maul's page-function source (pagefns.js): one
// JavaScript function expression (el, kind) => verdict.
//
//go:embed pagefns.js
var pageFunctions string

// Support is the support module (SupportFile) every compiled spec imports
// as SupportModule, to be written beside the spec. It carries the page
// functions as a string literal and runs them through locator.evaluate,
// so nothing is installed in the page and a page's own scripts cannot
// replace them.
func Support() []byte {
	lit, err := json.Marshal(pageFunctions)
	if err != nil {
		// Unreachable: a string always marshals.
		panic(err)
	}
	return []byte(strings.NewReplacer(
		"PAGE_FUNCTIONS_LITERAL", string(lit),
		"ACTION_TIMEOUT_MS", strconv.Itoa(ActionTimeoutMS),
		"INDETERMINATE_ANNOTATION", strconv.Quote(AnnotationIndeterminate),
	).Replace(supportTemplate))
}

// supportTemplate is maul-checks.ts. Every way a check can be unsure (an
// indeterminate page function, a text pattern JavaScript cannot compile)
// adds the AnnotationIndeterminate annotation before it throws, so the
// runner reports it as a check error, never a fail.
const supportTemplate = `// Copyright 2026 Bitwise Media Group Ltd.
// SPDX-License-Identifier: MIT
//
// Generated by maul (internal/checks/playwright). Do not edit: maul writes
// it beside every compiled check.
import { test, type Locator, type Page } from "@playwright/test";

type Verdict = { verdict: "pass" | "fail" | "indeterminate"; why: string[] };
type PageFunction = (el: Element, kind: string) => Verdict;
type Box = { x: number; y: number; width: number; height: number };

// pagefns.js, run in the page through locator.evaluate.
const PAGE_FUNCTIONS: string = PAGE_FUNCTIONS_LITERAL;
const pageFunction = new Function("return (" + PAGE_FUNCTIONS + ");")() as PageFunction;

// TIMEOUT bounds every retried judgement, as actionTimeout bounds actions.
const TIMEOUT = ACTION_TIMEOUT_MS;
const POLL = 100;

function indeterminate(what: string, why: string[]): never {
  const description = what + ": " + why.join("; ");
  test.info().annotations.push({ type: INDETERMINATE_ANNOTATION, description });
  throw new Error("maul: indeterminate " + description);
}

function fail(what: string, why: string[]): never {
  throw new Error("maul: " + what + " failed: " + why.join("; "));
}

function pause(): Promise<void> {
  return new Promise((resolve) => setTimeout(resolve, POLL));
}

// retry judges until a pass or TIMEOUT; the last verdict stands.
async function retry(what: string, once: () => Promise<Verdict>): Promise<void> {
  const deadline = Date.now() + TIMEOUT;
  for (;;) {
    const v = await once();
    if (v.verdict === "pass") return;
    if (Date.now() >= deadline) {
      if (v.verdict === "indeterminate") indeterminate(what, v.why);
      fail(what, v.why);
    }
    await pause();
  }
}

async function judged(loc: Locator, kind: string): Promise<Verdict> {
  await loc.scrollIntoViewIfNeeded();
  return loc.evaluate(pageFunction, kind);
}

async function box(loc: Locator, what: string): Promise<Box> {
  const b = await loc.boundingBox();
  if (!b) fail(what, ["the element has no box (not visible)"]);
  return b;
}

function px(n: number): string {
  return String(Math.round(n * 10) / 10);
}

function within(name: string, got: number, want: number, tolerance: number): string[] {
  return Math.abs(got - want) <= tolerance ? [] : [name + " " + px(got) + " not " + px(want) + " +/- " + px(tolerance)];
}

// relation judges two boxes measured in the same turn.
async function relation(what: string, a: Locator, b: Locator, ok: (p: Box, q: Box) => string[]): Promise<void> {
  await retry(what, async () => {
    const why = ok(await box(a, what), await box(b, what));
    return { verdict: why.length ? "fail" : "pass", why };
  });
}

function escapeRegExp(s: string): string {
  return s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

// pathPattern is a check's path pattern, "*" standing for any text. It is
// matched against the path, and the query too when the pattern has one.
function pathPattern(pattern: string): (u: URL) => boolean {
  const re = new RegExp("^" + pattern.split("*").map(escapeRegExp).join(".*") + "$");
  const withQuery = pattern.includes("?");
  return (u: URL) => re.test(withQuery ? u.pathname + u.search : u.pathname);
}

export const maul = {
  // settled waits for the page at its current URL to load: after a goto,
  // and after a click or key press whose navigation has committed.
  async settled(page: Page): Promise<void> {
    const now = page.url();
    await page.waitForURL((u: URL) => u.href === now);
  },

  async waitForPath(page: Page, pattern: string): Promise<void> {
    await page.waitForURL(pathPattern(pattern));
  },

  async expectPath(page: Page, pattern: string): Promise<void> {
    const matches = pathPattern(pattern);
    await retry("url " + pattern, async () => {
      const u = new URL(page.url());
      const why = matches(u) ? [] : ["the page is at " + u.pathname + u.search];
      return { verdict: why.length ? "fail" : "pass", why };
    });
  },

  // regex is a text pattern; one JavaScript cannot compile is a check
  // error, not a fail.
  regex(pattern: string): RegExp {
    try {
      return new RegExp(pattern);
    } catch (e) {
      indeterminate("text matches", [String(e)]);
    }
  },

  async scroll(loc: Locator, dx: number, dy: number): Promise<void> {
    await loc.evaluate(
      (el: Element, d: number[]) => el.scrollBy({ left: d[0], top: d[1], behavior: "instant" }),
      [dx, dy],
    );
  },

  async visible(loc: Locator): Promise<void> {
    await retry("visible", () => judged(loc, "visible"));
  },

  async legible(loc: Locator): Promise<void> {
    await retry("legible", () => judged(loc, "legible"));
  },

  // clickable: a failed hit test at the box centre is final; a pass is
  // confirmed by a trial click.
  async clickable(loc: Locator): Promise<void> {
    const v = await judged(loc, "hit");
    if (v.verdict !== "pass") fail("clickable", v.why);
    try {
      await loc.click({ trial: true, timeout: TIMEOUT });
    } catch (e) {
      fail("clickable", ["trial click: " + String(e).split("\n")[0]]);
    }
  },

  async leftOf(a: Locator, b: Locator, tolerance: number): Promise<void> {
    await relation("left-of", a, b, (p, q) =>
      p.x + p.width <= q.x + tolerance ? [] : ["right edge " + px(p.x + p.width) + " is past " + px(q.x)],
    );
  },

  async above(a: Locator, b: Locator, tolerance: number): Promise<void> {
    await relation("above", a, b, (p, q) =>
      p.y + p.height <= q.y + tolerance ? [] : ["bottom edge " + px(p.y + p.height) + " is below " + px(q.y)],
    );
  },

  async noOverlap(a: Locator, b: Locator, tolerance: number): Promise<void> {
    await relation("no-overlap", a, b, (p, q) => {
      const w = Math.min(p.x + p.width, q.x + q.width) - Math.max(p.x, q.x);
      const h = Math.min(p.y + p.height, q.y + q.height) - Math.max(p.y, q.y);
      return w <= tolerance || h <= tolerance ? [] : ["the boxes overlap by " + px(w) + "x" + px(h)];
    });
  },

  async equalSize(a: Locator, b: Locator, tolerance: number): Promise<void> {
    await relation("equal-size", a, b, (p, q) => [
      ...within("width", p.width, q.width, tolerance),
      ...within("height", p.height, q.height, tolerance),
    ]);
  },

  async aligned(a: Locator, b: Locator, axis: string, tolerance: number): Promise<void> {
    await relation("aligned " + axis, a, b, (p, q) =>
      axis === "x" ? within("x", p.x, q.x, tolerance) : within("y", p.y, q.y, tolerance),
    );
  },

  async size(loc: Locator, want: { width?: number; height?: number }, tolerance: number): Promise<void> {
    await retry("size", async () => {
      const b = await box(loc, "size");
      const why = [
        ...(want.width === undefined ? [] : within("width", b.width, want.width, tolerance)),
        ...(want.height === undefined ? [] : within("height", b.height, want.height, tolerance)),
      ];
      return { verdict: why.length ? "fail" : "pass", why };
    });
  },
};
`
